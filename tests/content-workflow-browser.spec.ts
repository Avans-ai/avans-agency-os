test("idea conversion preserves source and prevents a second conversion; daily date creates a draft", async ({ page }) => {
  await page.goto("/v2/clientes/epsa/contenido?seccion=ideas");
  await page.getByRole("button", { name: "Nueva idea", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "Nueva idea", exact: true });
  await modal.getByLabel("Idea", { exact: false }).first().fill("QA Idea del benchmark");
  await modal.getByLabel("Origen", { exact: true }).selectOption("Benchmark");
  await modal.getByLabel("Por qué resulta interesante").fill("Claridad del formato para explicar un proceso propio");
  await modal.getByLabel("URL de referencia").fill("https://example.com/referencia");
  await modal.getByLabel("Estado", { exact: false }).selectOption("Nueva");
  await modal.getByRole("button", { name: "Guardar en este navegador" }).click();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "QA Idea del benchmark", exact: true }) });
  await card.getByRole("button", { name: "Planificar contenido" }).click();
  const conversion = page.getByRole("dialog", { name: "Planificar idea como contenido" });
  await conversion.getByRole("button", { name: "Guardar borrador" }).click();
  await expect(conversion).toHaveCount(0);
  await expect(card.getByRole("link", { name: "Abrir contenido" })).toBeVisible();
  await expect(card.getByRole("button", { name: "Planificar contenido" })).toHaveCount(0);
  const record = (await contentData(page)).find((item: { values: { titulo: string } }) => item.values.titulo === "QA Idea del benchmark");
  expect(record.values).toMatchObject({ origen: "Benchmark", referencia: "https://example.com/referencia", estado: "Borrador" });
  expect(record.values.ideaId).toBeTruthy();
  await page.goto("/v2/clientes/epsa/contenido?seccion=calendario");
  await page.getByRole("button", { name: "Crear contenido el 2026-11-27", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Nuevo contenido" }).getByLabel("Fecha prevista")).toHaveValue("2026-11-27");
});
