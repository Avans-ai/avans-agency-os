import { test, expect, type Page, type Locator } from "@playwright/test";

test.use({ actionTimeout: 15000 });
async function createContent(page: Page, title: string, axisName: string) {
  await page.goto("/v2/clientes/epsa/contenido?seccion=piezas");
  await page.getByRole("button", { name: "Nuevo contenido", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "Nuevo contenido", exact: true });
  await modal.getByLabel("Título", { exact: false }).fill(title);
  await modal.getByLabel("Plan mensual", { exact: true }).selectOption({ label: "Plan noviembre QA" });
  await modal.getByLabel("Eje temático", { exact: true }).selectOption({ label: axisName });
  await modal.getByLabel("Idea", { exact: true }).fill("Explicar nuestro proceso con tres pasos");
  await modal.getByLabel("Bajada explicativa").fill("Una guía visual para entender los beneficios");
  await modal.getByLabel("Copy preliminar").fill("Conocé cómo trabajamos para mejorar los resultados.");
  await modal.getByLabel("Canal", { exact: true }).selectOption("LinkedIn");
  await modal.getByLabel("Formato", { exact: true }).selectOption("Carrusel");
  await modal.getByLabel("Fecha prevista").fill("2026-11-26");
  await modal.getByLabel("Horario (HH:MM)").fill("10:30");
  await modal.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  const detail = page.getByRole("dialog", { name: `Contenido: ${title}`, exact: true });
  await expect(detail).toBeVisible();
  return detail;
}
async function transition(detail: Locator, action: string, next: string, note?: string) {
  if (note) await detail.getByLabel("Comentario o devolución").fill(note);
  await detail.getByRole("button", { name: action, exact: true }).click();
  await expect(detail.getByText(next, { exact: true }).first()).toBeVisible();
}
async function contentData(page: Page) { return page.evaluate(() => JSON.parse(localStorage.getItem("avans-os:preview:v1:client:epsa:module:contenidos:piezas") || "null")?.value); }

