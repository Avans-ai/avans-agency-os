import { test, expect } from "@playwright/test";
import { seedKnowledge } from "../app/v2/os/knowledge/state";
import { newBrand, newItem } from "../app/v2/os/knowledge/benchmark";
import { osClients } from "../app/v2/os/os-data";

test("external Benchmark saves inspiration with an attachment and preserves client isolation", async ({ page }) => {
  const client = osClients.find((c) => c.slug === "epsa")!;
  const k = seedKnowledge(client);
  const own = { ...newBrand(client.name, true), items: [{ ...newItem("overview", { actor: "PM", at: "2026-11-20" }), values: { claim: "PRIVATE OWN BENCHMARK" } }] };
  const brand = { ...newBrand("Referente de prueba"), id: "rival-qa", type: "Referente" as const, items: [{ ...newItem("content", { actor: "PM", at: "2026-11-20" }), values: { links: "https://example.com/post", channel: "Instagram", summary: "Referencia con un beneficio claro" } }] };
  k.benchmark.brands = [own, brand];
  await page.addInitScript((state) => {
    const key = "avans-os:preview:v1:client:epsa:knowledge:v1";
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 1, value: state, savedAt: new Date().toISOString() }));
  }, k);
  await page.goto("/v2/clientes/epsa?view=benchmark");
  const region = page.getByRole("region", { name: "Benchmark", exact: true });
  await expect(region.locator("[id^=benchmark-propia]")).toHaveCount(0);
  await expect(region.getByText("PRIVATE OWN BENCHMARK")).toHaveCount(0);
  await expect(region.getByRole("heading", { name: "Referente de prueba", exact: true })).toBeVisible();
  await region.getByRole("button", { name: "Guardar en Banco de ideas" }).click();
  const dialog = page.getByRole("dialog", { name: "Guardar en Banco de ideas" });
  await dialog.getByLabel("Título de la idea").fill("Idea trazable QA");
  await dialog.getByLabel("Por qué resulta interesante").fill("Aprender de la secuencia sin copiar la pieza");
  await dialog.getByLabel("Adjuntar captura").setInputFiles({ name: "referencia.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9ZQmcAAAAASUVORK5CYII=", "base64") });
  await expect(dialog.getByRole("img", { name: "Captura de referencia de Referente de prueba" })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: test.info().outputPath("benchmark-idea-mobile.png") });
  await dialog.getByRole("button", { name: "Guardar idea", exact: true }).click();
  await expect(dialog.getByRole("status")).toContainText("Idea guardada");
  await page.setViewportSize({ width: 1440, height: 900 });
  const readIdeas = () => page.evaluate(() => JSON.parse(localStorage.getItem("avans-os:preview:v1:client:epsa:module:contenidos:ideas")!).value);
  const rows = await readIdeas();
  const idea = rows.find((r: { values: Record<string, string> }) => r.values.idea === "Idea trazable QA");
  expect(idea.values).toMatchObject({ origen: "Benchmark", sourceBenchmarkBrandId: "rival-qa", url: "https://example.com/post" });
  expect(idea.values.captura).toMatch(/^data:image\/png;base64,/);
  await page.reload();
  await region.getByRole("button", { name: "Guardar en Banco de ideas" }).click();
  await expect(dialog.getByRole("status")).toContainText("ya está en el Banco");
  expect((await readIdeas()).length).toBe(rows.length);
  await dialog.getByRole("link", { name: "Abrir Banco de ideas" }).click();
  await expect(page).toHaveURL(/\/contenido\?seccion=ideas/);
  await expect(page.getByText("Idea trazable QA", { exact: true }).first()).toBeVisible();
  await page.goto("/v2/clientes/aca/contenido?seccion=ideas");
  await expect(page.getByText("Idea trazable QA", { exact: true })).toHaveCount(0);
  const storedOwn = await page.evaluate(() => JSON.parse(localStorage.getItem("avans-os:preview:v1:client:epsa:knowledge:v1")!).value.benchmark.brands.find((b: { id: string }) => b.id === "own"));
  expect(storedOwn.items[0].values.claim).toBe("PRIVATE OWN BENCHMARK");
});
