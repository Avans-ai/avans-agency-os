#!/usr/bin/env python3
"""Regenerates lib/pptx/font-metrics.ts from the Figtree and Syne TTF files.

The generated table holds advance widths (in thousandths of an em) for the
characters the presentation generator measures when it fits text into the
boxes of the master template. It is a development tool: run it only when the
fonts of the master change.

Usage (requires `pip install fonttools`):
  python3 scripts/pptx-font-metrics.py \
    --figtree path/Figtree-Regular.ttf --figtree-bold path/Figtree-Bold.ttf \
    --syne path/Syne-Regular.ttf --syne-bold path/Syne-Bold.ttf \
    > lib/pptx/font-metrics.ts

The TTF files are the static instances published by Google Fonts (OFL).
"""
import argparse
import json

from fontTools.ttLib import TTFont

CHARS = (
    [chr(c) for c in range(32, 127)]
    + list("¡¿ÁÉÍÓÚÜÑáéíóúüñ·—–•…“”‘’%€$°ºª×")
)


def widths(path):
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    out = {}
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph is None:
            continue
        out[ch] = round(hmtx[glyph][0] * 1000 / upm)
    hhea = font["hhea"]
    return {
        "widths": out,
        "ascent": round(hhea.ascent * 1000 / upm),
        "descent": round(-hhea.descent * 1000 / upm),
        "lineGap": round(hhea.lineGap * 1000 / upm),
    }


def main():
    parser = argparse.ArgumentParser()
    for name in ("figtree", "figtree-bold", "syne", "syne-bold"):
        parser.add_argument(f"--{name}", required=True)
    args = vars(parser.parse_args())
    table = {
        "Figtree": {"regular": widths(args["figtree"]), "bold": widths(args["figtree_bold"])},
        "Syne": {"regular": widths(args["syne"]), "bold": widths(args["syne_bold"])},
    }
    print("// Generated by scripts/pptx-font-metrics.py from the Google Fonts TTF files.")
    print("// Advance widths in thousandths of an em. Do not edit by hand.")
    print("export type FontFaceMetrics = {")
    print("  widths: Record<string, number>;")
    print("  ascent: number;")
    print("  descent: number;")
    print("  lineGap: number;")
    print("};")
    print("export const FONT_METRICS: Record<")
    print("  string,")
    print("  { regular: FontFaceMetrics; bold: FontFaceMetrics }")
    print("> = " + json.dumps(table, ensure_ascii=False, indent=2) + ";")


if __name__ == "__main__":
    main()
